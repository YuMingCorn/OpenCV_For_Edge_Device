#!/usr/bin/env python3
"""Generate core/median_net.h: comparator networks that select the median of
9 and of 25 values, for the vector median_blur kernels.

    python3 tools/gen_median_net.py > core/median_net.h

Each network starts from Batcher's odd-even merge sort for the next power of
two. The padding wires would hold the maximum value, so a comparator that
touches one never moves anything and is dropped. Walking backwards from the
median output keeps only the comparators that can change it, and records for
each whether its min output, its max output or both are still read later.

The 0-1 principle proves the result: a comparator network selects rank k for
every input exactly when it does so for every input of 0s and 1s. The script
checks all 2^n binary inputs (bit-parallel) and exits 1 on any failure.
"""

import sys

import numpy as np


def batcher(n):
    """Comparators (i, j), i < j, of Batcher's odd-even merge sort on n = 2^m."""
    net = []
    p = 1
    while p < n:
        k = p
        while k >= 1:
            for j in range(k % p, n - k, 2 * k):
                for i in range(min(k, n - j - k)):
                    if (i + j) // (2 * p) == (i + j + k) // (2 * p):
                        net.append((i + j, i + j + k))
            k //= 2
        p *= 2
    return net


def median_net(n):
    size = 1
    while size < n:
        size *= 2
    net = [(i, j) for i, j in batcher(size) if j < n]
    need = {n // 2}
    kept = []
    for i, j in reversed(net):
        use_min, use_max = i in need, j in need
        if use_min or use_max:
            kept.append((i, j, use_min, use_max))
            need |= {i, j}
    kept.reverse()
    return kept


def verify(n, net):
    """0-1 principle over all 2^n inputs, one bit per input pattern."""
    x = np.arange(1 << n, dtype=np.uint32)
    wires = [np.packbits(((x >> k) & 1).astype(np.uint8)) for k in range(n)]
    for i, j, _, _ in net:
        lo = wires[i] & wires[j]
        hi = wires[i] | wires[j]
        wires[i], wires[j] = lo, hi
    ones = np.zeros(1 << n, dtype=np.uint32)
    for k in range(n):
        ones += (x >> k) & 1
    want = np.packbits((ones > n // 2).astype(np.uint8))
    return np.array_equal(wires[n // 2], want)


def emit(name, n, net):
    print(f"// {len(net)} comparators; the median ends on wire {n // 2}. X(i, j, use):")
    print("// use 1 = only the min (to wire i) is read later, 2 = only the max (to")
    print("// wire j), 3 = both.")
    print(f"#define {name.upper()}(X) \\")
    for k, (i, j, a, b) in enumerate(net):
        end = " \\" if k + 1 < len(net) else ""
        print(f"    X({i}, {j}, {int(a) | 2 * int(b)}){end}")


def main():
    nets = {9: median_net(9), 25: median_net(25)}
    for n, net in nets.items():
        if not verify(n, net):
            print(f"median network for {n} values failed the 0-1 check", file=sys.stderr)
            sys.exit(1)
    print("#ifndef MEDIAN_NET_H_")
    print("#define MEDIAN_NET_H_")
    print()
    print("// Generated by tools/gen_median_net.py; do not edit. Wires are window")
    print("// positions in row-major order (3x3 or 5x5). Both networks pass the 0-1")
    print("// principle check over all binary inputs, run by the generator.")
    print()
    emit("median9_net", 9, nets[9])
    print()
    emit("median25_net", 25, nets[25])
    print()
    print("#endif // MEDIAN_NET_H_")


if __name__ == "__main__":
    main()
